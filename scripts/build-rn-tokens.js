const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const sourcePath = path.join(rootDir, 'shared', 'design', 'tokens.json');
const outputPath = path.join(rootDir, 'src', 'components', 'tokens.generated.ts');

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

function toCamelCase(key) {
  return key.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

function mapKeys(value) {
  return Object.fromEntries(
    Object.entries(value).map(([key, entry]) => [toCamelCase(key), entry]),
  );
}

function numberFromWebUnit(entry) {
  const webValue = typeof entry === 'string' ? entry : entry.web;
  const parsed = Number.parseFloat(String(webValue).replace('px', ''));
  if (!Number.isFinite(parsed)) {
    throw new Error(`Cannot convert token value ${JSON.stringify(entry)} to an RN number`);
  }
  return parsed;
}

function mapNumericScale(scale) {
  return Object.fromEntries(
    Object.entries(scale).map(([key, entry]) => [toCamelCase(key), numberFromWebUnit(entry)]),
  );
}

function buildTheme(theme) {
  return {
    color: mapKeys(theme.color),
    spacing: mapNumericScale(source.spacing),
    radius: mapNumericScale(source.radius),
    font: mapNumericScale(source.font),
  };
}

const generated = {
  meta: {
    name: source.meta.name,
    version: source.meta.version,
    defaultTheme: source.meta.defaultTheme || 'dark',
  },
  light: buildTheme(source.themes.light),
  dark: buildTheme(source.themes.dark),
};

const file = `// This file is generated by scripts/build-rn-tokens.js. Do not edit manually.\n\nexport const tokenMeta = ${JSON.stringify(generated.meta, null, 2)} as const;\n\nexport const lightTokens = ${JSON.stringify(generated.light, null, 2)} as const;\n\nexport const darkTokens = ${JSON.stringify(generated.dark, null, 2)} as const;\n\nexport const themes = {\n  light: lightTokens,\n  dark: darkTokens,\n} as const;\n\nexport type CloudSeaThemeName = keyof typeof themes;\nexport type CloudSeaTokens = (typeof themes)[CloudSeaThemeName];\n`;

fs.writeFileSync(outputPath, file);
console.log(`Generated ${path.relative(rootDir, outputPath)}`);
